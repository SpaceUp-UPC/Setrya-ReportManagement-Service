import { randomUUID } from 'node:crypto';
import { rm } from 'node:fs/promises';
import { Test } from '@nestjs/testing';
import type { INestApplication } from '@nestjs/common';
import request from 'supertest';
import type { App } from 'supertest/types.js';
import { DataSource } from 'typeorm';
import { AppModule } from '../src/app.module.js';
import { configureApp } from '../src/app.setup.js';
import { signToken } from './support/jwt.js';

const BASE = '/api/v1/reports';
const BOM = '﻿';

interface ReportBody {
  id: string;
  type: string;
  spaceId: string;
  format: string;
  status: string;
}

function payload(overrides: Record<string, unknown> = {}) {
  return {
    type: 'HOME_HISTORY',
    spaceId: randomUUID(),
    periodStart: '2026-01-01T00:00:00.000Z',
    periodEnd: '2026-01-04T00:00:00.000Z',
    format: 'CSV',
    ...overrides,
  };
}

// Collects the response body as a Buffer so binary and BOM bytes stay intact.
function binaryParser(
  response: NodeJS.ReadableStream,
  callback: (error: Error | null, body: Buffer) => void,
) {
  const chunks: Buffer[] = [];
  response.on('data', (chunk: Buffer) => chunks.push(chunk));
  response.on('end', () => callback(null, Buffer.concat(chunks)));
}

describe('Reports (e2e)', () => {
  let app: INestApplication<App>;
  let dataSource: DataSource;

  // The authenticated user: becomes the requesterId of the reports it creates.
  const userId = randomUUID();
  let token: string;

  const http = () =>
    request.agent(app.getHttpServer()).set('Authorization', `Bearer ${token}`);
  const anonymous = () => request(app.getHttpServer());

  async function createReport(
    overrides: Record<string, unknown> = {},
  ): Promise<ReportBody> {
    const res = await http().post(BASE).send(payload(overrides)).expect(201);
    return res.body as ReportBody;
  }

  beforeAll(async () => {
    token = await signToken({ sub: userId });
    const moduleRef = await Test.createTestingModule({
      imports: [AppModule],
    }).compile();
    app = moduleRef.createNestApplication();
    configureApp(app);
    await app.init();
    dataSource = app.get(DataSource);
  });

  afterEach(async () => {
    // Remove the files generated by the test, then empty the table.
    const rows: { file_url: string | null }[] = await dataSource.query(
      'SELECT file_url FROM reports WHERE file_url IS NOT NULL',
    );
    await Promise.all(rows.map((row) => rm(row.file_url!, { force: true })));
    await dataSource.query('TRUNCATE TABLE reports');
  });

  afterAll(async () => {
    await app.close();
  });

  describe('POST /reports', () => {
    it('creates a report with status PENDING', async () => {
      const body = payload({ type: 'MAINTENANCE', format: 'PDF' });

      const res = await http().post(BASE).send(body).expect(201);

      expect(res.body).toMatchObject({
        type: 'MAINTENANCE',
        spaceId: body.spaceId,
        requesterId: userId,
        format: 'PDF',
        status: 'PENDING',
        fileUrl: null,
      });
      expect(res.body.id).toMatch(/^[0-9a-f-]{36}$/);
    });

    it('rejects an invalid format with 400', async () => {
      await http()
        .post(BASE)
        .send(payload({ format: 'XLSX' }))
        .expect(400);
    });

    it('rejects an invalid spaceId with 400', async () => {
      await http()
        .post(BASE)
        .send(payload({ spaceId: 'not-a-uuid' }))
        .expect(400);
    });

    it('takes requesterId from the token and ignores one sent in the body', async () => {
      const res = await http()
        .post(BASE)
        .send(payload({ requesterId: randomUUID() }))
        .expect(201);

      expect(res.body.requesterId).toBe(userId);
    });

    it('uses the sub of whichever token is presented', async () => {
      const otherUser = randomUUID();
      const otherToken = await signToken({ sub: otherUser, alg: 'HS512' });

      const res = await anonymous()
        .post(BASE)
        .set('Authorization', `Bearer ${otherToken}`)
        .send(payload())
        .expect(201);

      expect(res.body.requesterId).toBe(otherUser);
    });
  });

  describe('authentication', () => {
    it('keeps GET /health public', async () => {
      const res = await anonymous().get('/api/v1/health').expect(200);

      expect(res.body).toEqual({ status: 'ok' });
    });

    it.each([
      ['GET', BASE],
      ['POST', BASE],
      ['GET', `${BASE}/${randomUUID()}`],
      ['POST', `${BASE}/${randomUUID()}/generate`],
      ['GET', `${BASE}/${randomUUID()}/download`],
    ])(
      'returns 401 with a JSON body for %s %s without a token',
      async (method, url) => {
        const res = await anonymous()[method === 'GET' ? 'get' : 'post'](url);

        expect(res.status).toBe(401);
        expect(res.headers['content-type']).toContain('application/json');
        expect(res.body).toMatchObject({ statusCode: 401 });
      },
    );

    it('does not create a report without a token', async () => {
      await anonymous().post(BASE).send(payload()).expect(401);

      const rows: unknown[] = await dataSource.query('SELECT 1 FROM reports');
      expect(rows).toHaveLength(0);
    });

    it('returns 401 for a token signed with another secret', async () => {
      const forged = await signToken({
        secret: 'some-other-secret-0123456789abcdef',
      });

      await anonymous()
        .get(BASE)
        .set('Authorization', `Bearer ${forged}`)
        .expect(401);
    });

    it('returns 401 for an expired token', async () => {
      const expired = await signToken({ expiresInSeconds: -60 });

      await anonymous()
        .get(BASE)
        .set('Authorization', `Bearer ${expired}`)
        .expect(401);
    });

    it('returns 401 for a malformed token', async () => {
      await anonymous()
        .get(BASE)
        .set('Authorization', 'Bearer not.a.jwt')
        .expect(401);
    });
  });

  describe('GET /reports/:id', () => {
    it('returns an existing report', async () => {
      const created = await createReport();

      const res = await http().get(`${BASE}/${created.id}`).expect(200);

      expect(res.body).toMatchObject({ id: created.id, status: 'PENDING' });
    });

    it('returns 404 for a missing id', async () => {
      await http().get(`${BASE}/${randomUUID()}`).expect(404);
    });

    it('returns 400 for a malformed id', async () => {
      await http().get(`${BASE}/not-a-uuid`).expect(400);
    });
  });

  describe('GET /reports (list)', () => {
    it('filters by spaceId, type and status', async () => {
      const spaceA = randomUUID();
      const spaceB = randomUUID();
      await createReport({ spaceId: spaceA, type: 'INSTALLATION' });
      const homeA = await createReport({ spaceId: spaceA, type: 'HOME_HISTORY' });
      await createReport({ spaceId: spaceB, type: 'HOME_HISTORY' });
      await http().post(`${BASE}/${homeA.id}/generate`).expect(201);

      const bySpace = await http().get(BASE).query({ spaceId: spaceA }).expect(200);
      expect(bySpace.body.total).toBe(2);
      expect(
        (bySpace.body.items as ReportBody[]).every((r) => r.spaceId === spaceA),
      ).toBe(true);

      const byType = await http().get(BASE).query({ type: 'HOME_HISTORY' }).expect(200);
      expect(byType.body.total).toBe(2);

      const byStatus = await http().get(BASE).query({ status: 'READY' }).expect(200);
      expect(byStatus.body.total).toBe(1);
      expect(byStatus.body.items[0].id).toBe(homeA.id);

      const combined = await http()
        .get(BASE)
        .query({ spaceId: spaceA, type: 'HOME_HISTORY', status: 'READY' })
        .expect(200);
      expect(combined.body.total).toBe(1);

      const none = await http()
        .get(BASE)
        .query({ spaceId: spaceB, status: 'READY' })
        .expect(200);
      expect(none.body).toMatchObject({ items: [], total: 0 });
    });

    it('paginates results', async () => {
      const spaceId = randomUUID();
      for (let i = 0; i < 5; i++) {
        await createReport({ spaceId });
      }

      const page1 = await http().get(BASE).query({ spaceId, page: 1, limit: 2 }).expect(200);
      const page2 = await http().get(BASE).query({ spaceId, page: 2, limit: 2 }).expect(200);
      const page3 = await http().get(BASE).query({ spaceId, page: 3, limit: 2 }).expect(200);

      expect(page1.body).toMatchObject({ total: 5, page: 1, limit: 2 });
      expect(page1.body.items).toHaveLength(2);
      expect(page2.body.items).toHaveLength(2);
      expect(page3.body.items).toHaveLength(1);

      const ids = [page1, page2, page3].flatMap((res) =>
        (res.body.items as ReportBody[]).map((r) => r.id),
      );
      expect(new Set(ids).size).toBe(5);
    });

    it('uses default pagination and rejects invalid values', async () => {
      const res = await http().get(BASE).expect(200);
      expect(res.body).toMatchObject({ items: [], total: 0, page: 1, limit: 20 });

      await http().get(BASE).query({ limit: 101 }).expect(400);
      await http().get(BASE).query({ page: 0 }).expect(400);
      await http().get(BASE).query({ status: 'DONE' }).expect(400);
    });
  });

  describe('generate and download', () => {
    it('generates a CSV, marks it READY and downloads it with BOM and header', async () => {
      const created = await createReport({ type: 'HOME_HISTORY', format: 'CSV' });

      const generated = await http().post(`${BASE}/${created.id}/generate`).expect(201);
      expect(generated.body).toMatchObject({ id: created.id, status: 'READY' });
      expect(generated.body.fileUrl).toEqual(expect.any(String));

      const res = await http()
        .get(`${BASE}/${created.id}/download`)
        .buffer(true)
        .parse(binaryParser)
        .expect(200);

      expect(res.headers['content-type']).toContain('text/csv');
      expect(res.headers['content-disposition']).toContain(`${created.id}.csv`);

      const text = (res.body as Buffer).toString('utf-8');
      expect(text.startsWith(BOM)).toBe(true);
      const [header, ...rows] = text.slice(BOM.length).split('\n');
      expect(header).toBe('timestamp;temperature;humidity');
      expect(rows).toHaveLength(3);
    });

    it('generates a PDF, marks it READY and downloads a valid PDF', async () => {
      const created = await createReport({ type: 'INSTALLATION', format: 'PDF' });

      const generated = await http().post(`${BASE}/${created.id}/generate`).expect(201);
      expect(generated.body).toMatchObject({ id: created.id, status: 'READY' });

      const res = await http()
        .get(`${BASE}/${created.id}/download`)
        .buffer(true)
        .parse(binaryParser)
        .expect(200);

      expect(res.headers['content-type']).toContain('application/pdf');
      expect((res.body as Buffer).subarray(0, 4).toString('latin1')).toBe('%PDF');
    });

    it('returns 409 when downloading before generating', async () => {
      const created = await createReport();

      await http().get(`${BASE}/${created.id}/download`).expect(409);
    });

    it('returns 404 when downloading a missing report', async () => {
      await http().get(`${BASE}/${randomUUID()}/download`).expect(404);
    });

    it('returns 404 when generating a missing report', async () => {
      await http().post(`${BASE}/${randomUUID()}/generate`).expect(404);
    });
  });
});
